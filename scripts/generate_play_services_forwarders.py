#!/usr/bin/env python3
"""Generates src/play_services/litert_forwarders.inc.

In the Play services runtime mode the plugin does not ship libLiteRt.so. Google
Play services hands the app a LiteRtRuntimeCApiStruct function table instead.
flutter_litert_runtime.c exports one forwarder per LiteRt C function that the
Dart bindings look up (lib/src/bindings/litert_ffi.dart), so the Dart side keeps
binding plain C symbols and never indexes the table itself.

The forwarders are generated from the table header shipped in the
play-services-litert AAR, so every parameter list is Google's own. The C
compiler then checks each forwarder against the public LiteRt declaration of
the same name, and flutter_litert_runtime.c static_asserts that every slot lies
in the ABI 1.0.0 prefix that Play services guarantees.

Usage (run from the repository root):

  python3 -I scripts/generate_play_services_forwarders.py \\
      <AAR>/prefab/modules/litert_compiledmodel_gms_client/include

Re-run it whenever litert_ffi.dart binds a new LiteRt function or the
play-services-litert version changes, and commit the result.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DART_BINDINGS = ROOT / "lib" / "src" / "bindings" / "litert_ffi.dart"
OUTPUT = ROOT / "src" / "play_services" / "litert_forwarders.inc"
TABLE_HEADER = pathlib.Path("litert") / "c" / "internal" / "litert_runtime_c_api.h"

FIELD_RE = re.compile(
    # "// litert_model.h: LiteRtFoo", sometimes wrapped onto a second line.
    r"//\s*\S+\.h:\s*(?:\n\s*//\s*)?(LiteRt\w+)\s*\n"
    r"\s*([^;{}]*?)\(\s*\*\s*(litert_\w+)\s*\)\s*\(([^;]*?)\)\s*;",
    re.S,
)


def split_params(params):
    """Splits a C parameter list on top-level commas."""
    parts, depth, current = [], 0, ""
    for ch in params:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(current)
            current = ""
        else:
            current += ch
    if current.strip():
        parts.append(current)
    return [" ".join(p.split()) for p in parts]


def param_name(param):
    pointer = re.search(r"\(\s*\*\s*(\w+)\s*\)", param)
    if pointer:
        return pointer.group(1)
    match = re.search(r"(\w+)\s*(\[\s*\])?$", param)
    if not match:
        raise ValueError(f"cannot find a parameter name in {param!r}")
    return match.group(1)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    header = pathlib.Path(sys.argv[1]) / TABLE_HEADER
    source = header.read_text()
    fields = {}
    for public, ret, field, params in FIELD_RE.findall(source):
        fields[public] = (" ".join(ret.split()), field, split_params(params))

    wanted = sorted(set(re.findall(r"'(LiteRt\w+)'", DART_BINDINGS.read_text())))
    missing = [name for name in wanted if name not in fields]
    if missing:
        sys.exit(f"not in the Play services table: {', '.join(missing)}")

    lines = [
        "// Generated by scripts/generate_play_services_forwarders.py from",
        "// play-services-litert's litert_runtime_c_api.h. Do not edit by hand.",
        "//",
        "// FLUTTER_LITERT_FORWARD_STATUS / _VOID(LiteRt name, table field,",
        "//                                       (parameters), (arguments))",
        "",
    ]
    for name in wanted:
        ret, field, params = fields[name]
        if params == ["void"]:
            params = []
        args = ", ".join(param_name(p) for p in params)
        if ret == "void":
            macro, head = "FLUTTER_LITERT_FORWARD_VOID", ""
        elif ret == "LiteRtStatus":
            macro, head = "FLUTTER_LITERT_FORWARD_STATUS", ""
        else:
            sys.exit(f"{name} returns {ret}; add a forwarder macro for it")
        indent = " " * (len(macro) + 1)
        lines.append(
            f"{macro}({head}{name}, {field},\n"
            f"{indent}({', '.join(params) or 'void'}),\n"
            f"{indent}({args}))"
        )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(wanted)} forwarders to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
